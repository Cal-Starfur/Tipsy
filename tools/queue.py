#!/usr/bin/env python3
"""Build queue. `queue.py next` prints the one ready item; `queue.py done ID` marks it
and regenerates build_queue.md (graph for humans). Agents never need to read the .md."""
import json, sys, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
J = R / "build_queue.json"
q = json.loads(J.read_text()); N = {n["id"]: n for n in q["nodes"]}

def ready():
    return [n for n in q["nodes"] if n["status"] == "pending"
            and all(N[d]["status"] == "done" for d in n["deps"])]

def md():
    mark = {"done": "x", "pending": " ", "blocked": "!"}
    L = ["# Build queue (generated by tools/queue.py; edit build_queue.json)", "",
         "Agents: run `python3 tools/queue.py next`, build it per CLAUDE.md, then",
         "`python3 tools/queue.py done <id>`, commit, push to `consistency-pass`.", "",
         "```mermaid", "graph LR"]
    for n in q["nodes"]:
        L.append(f'  {n["id"].replace(".","_")}["{n["id"]}: {n["title"][:40]}"]:::{n["status"]}')
        for d in n["deps"]: L.append(f'  {d.replace(".","_")} --> {n["id"].replace(".","_")}')
    L += ["  classDef done fill:#9f9", "  classDef blocked fill:#fc9", "```", ""]
    L += [f'- [{mark[n["status"]]}] `{n["id"]}` {n["title"]}' + (f' ({n["note"]})' if n.get("note") else "")
          for n in q["nodes"]]
    (R / "build_queue.md").write_text("\n".join(L) + "\n")

if sys.argv[1:2] == ["next"]:
    r = ready(); print(json.dumps(r[0]) if r else "NONE READY")
elif sys.argv[1:2] == ["done"]:
    N[sys.argv[2]]["status"] = "done"; J.write_text(json.dumps(q, indent=0)); md()
else: md()
