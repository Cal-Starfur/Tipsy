#!/usr/bin/env python3
"""Build queue. `queue.py next` prints the one ready item; `queue.py built ID [test-link]` marks it built and awaiting Sir; `signoff ID` (Sir only) marks it done
and regenerates build_queue.md (graph for humans). Agents never need to read the .md."""
import json, sys, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
J = R / "build_queue.json"
q = json.loads(J.read_text()); N = {n["id"]: n for n in q["nodes"]}

def ready():
    return [n for n in q["nodes"] if n["status"] == "pending"
            and all(N[d]["status"] in ("done","built") for d in n["deps"])]

def md():
    mark = {"done": "x", "pending": " ", "blocked": "!", "built": "?"}
    L = ["# Build plan (generated by tools/queue.py; edit build_queue.json)", "",
         "Agents: run `python3 tools/queue.py next`, build it, then `python3 tools/queue.py done <id>`,",
         "commit, push to `consistency-pass`. `[ ]` pending, `[?]` built, awaiting Sir's test, `[x]` signed off, `[!]` waiting on Sir.", ""]
    deps = [n for n in q["nodes"] if n["deps"]]
    if deps:
        L += ["## Dependencies", "```mermaid", "graph LR"]
        for n in deps:
            for d in n["deps"]: L.append(f'  {d.replace(".","_")} --> {n["id"].replace(".","_")}')
        L += ["```", ""]
    groups = list(dict.fromkeys(n["group"] for n in q["nodes"]))
    for g in groups:
        L += [f"## {g}"]
        L += [f'- [{mark[n["status"]]}] `{n["id"]}` {n["title"]}' + (f' ({n["note"]})' if n.get("note") else "")
              + (f' [test]({n["test"]})' if n.get("test") else "") + (f' [{n["spec"]}]' if n.get("spec") else "") for n in q["nodes"] if n["group"] == g]
        L.append("")
    (R / "build_queue.md").write_text("\n".join(L))

if sys.argv[1:2] == ["next"]:
    r = ready(); print(json.dumps(r[0]) if r else "NONE READY")
elif sys.argv[1:2] in (["built"], ["signoff"]):
    N[sys.argv[2]]["status"] = "built" if sys.argv[1] == "built" else "done"
    if len(sys.argv) > 3: N[sys.argv[2]]["test"] = sys.argv[3]
    J.write_text(json.dumps(q, indent=0)); md()
else: md()
